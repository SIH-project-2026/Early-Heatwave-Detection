interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  currentLanguageOption: LanguageOption;
  isHindi: boolean;
  t: (key: string, fallback?: string) => string;
  translateText: (text: string, lang?: LanguageCode) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    try {
      const saved = (localStorage.getItem('app_language') || localStorage.getItem('user_language')) as LanguageCode;
      if (saved && LANGUAGES.some((l) => l.code === saved)) {
        return saved;
      }
    } catch {
      // Ignore localStorage errors
    }
    return 'en';
  });

  const setLanguage = (lang: LanguageCode) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('app_language', lang);
      localStorage.setItem('user_language', lang);
      localStorage.setItem('agent_chat_language', lang);
      window.dispatchEvent(new CustomEvent('app_language_changed', { detail: lang }));
      window.dispatchEvent(new CustomEvent('languageChange', { detail: lang }));
    } catch {
      // Ignore
    }
    applyDomTranslations(lang);
    setTimeout(() => applyDomTranslations(lang), 60);
  };

  const currentLanguageOption = LANGUAGES.find((l) => l.code === language) || LANGUAGES[0];
  const isHindi = language === 'hi';

  const t = (key: string, fallback?: string): string => {
    if (!key) return fallback || '';

    // 1. Direct translation key lookup
    if (TRANSLATIONS[key] && TRANSLATIONS[key][language]) {
      return TRANSLATIONS[key][language]!;
    }

    // 2. Direct phrase lookup
    const lower = key.toLowerCase().trim();
    const mappedKey = PHRASE_LOOKUP[lower];
    if (mappedKey && TRANSLATIONS[mappedKey] && TRANSLATIONS[mappedKey][language]) {
      return TRANSLATIONS[mappedKey][language]!;
    }

    // 3. Fallback to comprehensive DOM Translator dictionary
    const dictTrans = domTranslateText(fallback || key, language);
    if (dictTrans && dictTrans !== (fallback || key)) {
      return dictTrans;
    }

    // 4. Fallback to English translation
    if (TRANSLATIONS[key] && TRANSLATIONS[key]['en']) {
      return TRANSLATIONS[key]['en']!;
    }
    if (mappedKey && TRANSLATIONS[mappedKey] && TRANSLATIONS[mappedKey]['en']) {
      return TRANSLATIONS[mappedKey]['en']!;
    }

    // 5. Fallback or raw key
    return fallback || key;
  };

  const translate = (text: string, targetLang?: LanguageCode) => {
    return domTranslateText(text, targetLang || language);
  };

  useEffect(() => {
    document.documentElement.lang = language;
    applyDomTranslations(language);
    const timer = setTimeout(() => applyDomTranslations(language), 60);
    return () => clearTimeout(timer);
  }, [language]);

  useEffect(() => {
    initDomAutoTranslator(language);
  }, []);

  return (
    <LanguageContext.Provider value={{ language, setLanguage, currentLanguageOption, isHindi, t, translateText: translate }}>
      {children}
    </LanguageContext.Provider>
  );
};

// eslint-disable-next-line react-refresh/only-export-components
export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
