/**
 * Regex to detect any regional Indian script characters:
 * Devanagari (\u0900-\u097F), Bengali/Assamese (\u0980-\u09FF), Gurmukhi (\u0A00-\u0A7F),
 * Gujarati (\u0A80-\u0AFF), Odia (\u0B00-\u0B7F), Tamil (\u0B80-\u0BFF),
 * Telugu (\u0C00-\u0C7F), Kannada (\u0C80-\u0CFF), Malayalam (\u0D00-\u0D7F)
 */
export const INDIAN_SCRIPT_REGEX = /[\u0900-\u0D7F]/;

export const SCRIPT_RANGES: Record<LanguageCode, RegExp> = {
  en: /^[A-Za-z0-9\s.,/\\:;+\-%°#_@!?()[\]{}|'"—–\u20B9\u00A9\u00AE]*$/,
  hi: /[\u0900-\u097F]/,
  mr: /[\u0900-\u097F]/,
  bn: /[\u0980-\u09FF]/,
  as: /[\u0980-\u09FF]/,
  pa: /[\u0A00-\u0A7F]/,
  gu: /[\u0A80-\u0AFF]/,
  or: /[\u0B00-\u0B7F]/,
  ta: /[\u0B80-\u0BFF]/,
  te: /[\u0C00-\u0C7F]/,
  kn: /[\u0C80-\u0CFF]/,
  ml: /[\u0D00-\u0D7F]/,
};

export function containsIndianScript(text: string): boolean {
  return INDIAN_SCRIPT_REGEX.test(text);
}

// Reverse mapping: lowerCase(translatedText) -> canonical English text
const REVERSE_LOOKUP = new Map<string, string>();
let SORTED_REVERSE_KEYS: string[] = [];

function populateReverseDictionary() {
  Object.entries(COMPREHENSIVE_DICTIONARY).forEach(([engKey, translations]) => {
    // Generate clean capitalized English fallback title
    const canonical = engKey
      .split(' ')
      .map((w) => (w ? w.charAt(0).toUpperCase() + w.slice(1) : ''))
      .join(' ');

    Object.values(translations).forEach((val) => {
      if (val) {
        const lower = val.trim().toLowerCase();
        if (lower && !REVERSE_LOOKUP.has(lower)) {
          REVERSE_LOOKUP.set(lower, canonical);
        }
      }
    });
  });

  SORTED_REVERSE_KEYS = Array.from(REVERSE_LOOKUP.keys()).sort((a, b) => b.length - a.length);
}

populateReverseDictionary();

/**
 * Allows external modules (such as LanguageContext) to register additional high-priority canonical translations
 */
export function registerTranslations(translations: Record<string, Partial<Record<LanguageCode, string>>>) {
  Object.values(translations).forEach((item) => {
    const enVal = item?.en;
    if (!enVal) return;

    // Register into normalized forward lookup
    const enLower = enVal.trim().toLowerCase();
    if (!NORMALIZED_LOOKUP[enLower]) {
      NORMALIZED_LOOKUP[enLower] = item;
    }

    // Register into reverse lookup with exact English casing
    Object.entries(item).forEach(([lang, val]) => {
      if (lang !== 'en' && val) {
        const lower = val.trim().toLowerCase();
        REVERSE_LOOKUP.set(lower, enVal);
      }
    });
  });

  SORTED_PHRASE_KEYS = Object.keys(NORMALIZED_LOOKUP).sort((a, b) => b.length - a.length);
  SORTED_REVERSE_KEYS = Array.from(REVERSE_LOOKUP.keys()).sort((a, b) => b.length - a.length);
}

/**
 * Reverses a translated Indian language string back to clean English
 */
export function translateToEnglish(rawText: string): string {
  if (!rawText) return rawText;
  const trimmed = rawText.trim();
  if (!trimmed) return rawText;

  // 1. Direct exact match in reverse lookup
  const lower = trimmed.toLowerCase();
  if (REVERSE_LOOKUP.has(lower)) {
    const canonical = REVERSE_LOOKUP.get(lower)!;
    const leadingWs = rawText.match(/^\s*/)?.[0] || '';
    const trailingWs = rawText.match(/\s*$/)?.[0] || '';
    return `${leadingWs}${canonical}${trailingWs}`;
  }

  // If text does not contain any Indian script characters, return as is
  if (!INDIAN_SCRIPT_REGEX.test(trimmed)) {
    return rawText;
  }

  // 2. Sub-phrase reverse replacement (longest translated phrases first)
  let result = rawText;
  for (const phrase of SORTED_REVERSE_KEYS) {
    if (phrase.length < 2) continue;
    if (result.toLowerCase().includes(phrase)) {
      const canonical = REVERSE_LOOKUP.get(phrase);
      if (canonical) {
        const regex = new RegExp(escapeRegExp(phrase), 'gi');
        result = result.replace(regex, canonical);
      }
    }
  }

  return result;
}

/**
 * Intelligent forward text translator:
 * 1. Exact match in dictionary
 * 2. Longest substring phrase substitution
 * 3. Individual word replacement
 */
export function translateText(rawText: string, targetLang: LanguageCode): string {
  if (!rawText || targetLang === 'en') return rawText;

  const trimmed = rawText.trim();
  if (!trimmed) return rawText;

  // If text is purely numeric, dates, symbols, or formatting tokens, skip
  if (/^[0-9\s.,/\\:;+\-%°#_@!?()[\]{}|]+$/.test(trimmed)) {
    return rawText;
  }

  // If text contains Indian script from a previous language render, first normalize it to English!
  const englishBase = INDIAN_SCRIPT_REGEX.test(trimmed) ? translateToEnglish(trimmed) : trimmed;
  const lower = englishBase.toLowerCase();

  // 1. Direct full match
  if (NORMALIZED_LOOKUP[lower] && NORMALIZED_LOOKUP[lower][targetLang]) {
    const translated = NORMALIZED_LOOKUP[lower][targetLang]!;
    const leadingWs = rawText.match(/^\s*/)?.[0] || '';
    const trailingWs = rawText.match(/\s*$/)?.[0] || '';
    return `${leadingWs}${translated}${trailingWs}`;
  }

  // 2. Sub-phrase replacement for compound text
  let result = englishBase;

  for (const phrase of SORTED_PHRASE_KEYS) {
    if (phrase.length < 3) continue;

    const translation = NORMALIZED_LOOKUP[phrase]?.[targetLang];
    if (!translation) continue;

    const regex = new RegExp(`\\b${escapeRegExp(phrase)}\\b`, 'gi');
    if (regex.test(result)) {
      result = result.replace(regex, translation);
    }
  }

  return result;
}

function escapeRegExp(str: string) {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Global DOM State for original text preservation and observer management
const originalTextMap = new WeakMap<Node, string>();
let domObserver: MutationObserver | null = null;
let currentLanguage: LanguageCode = 'en';
let isTranslating = false;
let rafHandle: number | null = null;
let isInitialized = false;

// Tags that should NEVER be translated
const IGNORED_TAGS = new Set([
  'SCRIPT',
  'STYLE',
  'NOSCRIPT',
  'CODE',
  'PRE',
  'SVG',
  'CANVAS',
  'AUDIO',
  'VIDEO',
  'SOURCE',
]);

/**
 * Traverses a node and translates its text children and attributes.
 * In English mode (lang === 'en'), it guarantees that every node is restored to English.
 */
function walkAndTranslate(root: Node, lang: LanguageCode) {
  if (!root) return;

  if (root.nodeType === Node.TEXT_NODE) {
    const textNode = root as Text;
    const currentVal = (textNode.nodeValue || '').trim();
    if (!currentVal) return;

    // 1. If this node is ALREADY rendered in the target language script (e.g. by React t()),
    // do NOT touch or clobber it!
    if (lang === 'en') {
      if (!INDIAN_SCRIPT_REGEX.test(currentVal)) {
        originalTextMap.set(textNode, textNode.nodeValue || '');
        return;
      }
    } else {
      const scriptRegex = SCRIPT_RANGES[lang];
      if (scriptRegex && scriptRegex.test(currentVal)) {
        return;
      }
    }

    let original = originalTextMap.get(textNode);

    // If original is missing or contains an Indian script, resolve canonical English:
    if (original === undefined || INDIAN_SCRIPT_REGEX.test(original)) {
      if (INDIAN_SCRIPT_REGEX.test(currentVal)) {
        original = translateToEnglish(currentVal);
      } else {
        original = textNode.nodeValue || '';
      }
      originalTextMap.set(textNode, original);
    }

    if (lang === 'en') {
      const targetEnglish = original || translateToEnglish(textNode.nodeValue || '');
      if (textNode.nodeValue !== targetEnglish) {
        textNode.nodeValue = targetEnglish;
      }
    } else {
      const translated = translateText(original, lang);
      if (translated && textNode.nodeValue !== translated) {
        textNode.nodeValue = translated;
      }
    }
    return;
  }

  if (root.nodeType === Node.ELEMENT_NODE) {
    const el = root as HTMLElement;

    if (IGNORED_TAGS.has(el.tagName) || el.getAttribute('data-no-translate') === 'true') {
      return;
    }

    // Translate placeholder attributes on inputs
    if (el.hasAttribute('placeholder')) {
      let origPlaceholder = el.getAttribute('data-orig-placeholder') || el.getAttribute('placeholder') || '';
      if (INDIAN_SCRIPT_REGEX.test(origPlaceholder)) {
        origPlaceholder = translateToEnglish(origPlaceholder);
      }
      if (!el.hasAttribute('data-orig-placeholder') || INDIAN_SCRIPT_REGEX.test(el.getAttribute('data-orig-placeholder') || '')) {
        el.setAttribute('data-orig-placeholder', origPlaceholder);
      }
      if (lang === 'en') {
        el.setAttribute('placeholder', origPlaceholder);
      } else {
        el.setAttribute('placeholder', translateText(origPlaceholder, lang));
      }
    }

    // Translate title attribute
    if (el.hasAttribute('title')) {
      let origTitle = el.getAttribute('data-orig-title') || el.getAttribute('title') || '';
      if (INDIAN_SCRIPT_REGEX.test(origTitle)) {
        origTitle = translateToEnglish(origTitle);
      }
      if (!el.hasAttribute('data-orig-title') || INDIAN_SCRIPT_REGEX.test(el.getAttribute('data-orig-title') || '')) {
        el.setAttribute('data-orig-title', origTitle);
      }
      if (lang === 'en') {
        el.setAttribute('title', origTitle);
      } else {
        el.setAttribute('title', translateText(origTitle, lang));
      }
    }

    // Walk child nodes
    const children = el.childNodes;
    for (let i = 0; i < children.length; i++) {
      walkAndTranslate(children[i], lang);
    }
  }
}

/**
 * Triggers safe, high-performance DOM translation for the entire document
 */
export function applyDomTranslations(lang: LanguageCode) {
  currentLanguage = lang;

  if (typeof document === 'undefined') return;

  if (rafHandle) {
    cancelAnimationFrame(rafHandle);
  }

  rafHandle = requestAnimationFrame(() => {
    isTranslating = true;
    try {
      const target = document.getElementById('root') || document.body;
      if (target) {
        walkAndTranslate(target, lang);
      }
    } catch (err) {
      console.warn('[DOMTranslator] Translation update warning:', err);
    } finally {
      isTranslating = false;
    }
  });
}

/**
 * Initializes the real-time MutationObserver to detect DOM changes and auto-translate newly mounted elements
 */
export function initDomAutoTranslator(initialLang: LanguageCode = 'en') {
  if (typeof window === 'undefined' || typeof document === 'undefined') return;

  currentLanguage = initialLang;

  if (domObserver) {
    domObserver.disconnect();
  }

  domObserver = new MutationObserver((mutations) => {
    if (isTranslating) return;

    let hasChanges = false;
    for (const mutation of mutations) {
      if (mutation.type === 'childList') {
        for (let i = 0; i < mutation.addedNodes.length; i++) {
          const node = mutation.addedNodes[i];
          if (node.nodeType === Node.ELEMENT_NODE) {
            const el = node as HTMLElement;
            if (el.getAttribute('data-no-translate') === 'true') continue;
          }
          hasChanges = true;
          break;
        }
        if (hasChanges) break;
      }
      if (mutation.type === 'characterData') {
        const textNode = mutation.target as Text;
        const currentVal = (textNode.nodeValue || '').trim();
        if (!currentVal) continue;

        // If already in target language script, ignore
        if (currentLanguage !== 'en') {
          const script = SCRIPT_RANGES[currentLanguage];
          if (script && script.test(currentVal)) {
            continue;
          }
        }

        const prevOrig = originalTextMap.get(textNode);

        // If currentVal is genuine English text from React re-render:
        if (!INDIAN_SCRIPT_REGEX.test(currentVal)) {
          if (currentVal !== prevOrig) {
            originalTextMap.set(textNode, currentVal);
            if (currentLanguage !== 'en') {
              hasChanges = true;
              break;
            }
          }
        } else if (currentLanguage === 'en') {
          // If Indian script characters appeared while in English mode, trigger English restore
          hasChanges = true;
          break;
        }
      }
    }

    if (hasChanges) {
      applyDomTranslations(currentLanguage);
    }
  });

  const target = document.getElementById('root') || document.body;
  if (target) {
    domObserver.observe(target, {
      childList: true,
      subtree: true,
      characterData: true,
    });
  }

  if (!isInitialized) {
    isInitialized = true;
    // Listen to custom language events & navigation changes
    window.addEventListener('app_language_changed', (e: any) => {
      const code = e?.detail as LanguageCode;
      if (code) {
        applyDomTranslations(code);
        setTimeout(() => applyDomTranslations(code), 60);
      }
    });

    window.addEventListener('popstate', () => {
      setTimeout(() => applyDomTranslations(currentLanguage), 50);
    });
  }

  applyDomTranslations(initialLang);
  setTimeout(() => applyDomTranslations(initialLang), 60);
}
