def resolve_state_fund(region_id: str):
    """
    Intelligently maps any city, district, or state input query 
    to the official Government SDRF state allocation record.
    """
    clean_id = (region_id or "kanpur").lower().strip().replace("-", " ")
    
    # 1. Exact match check
    for state_key, data in OFFICIAL_SDRF_ALLOCATIONS.items():
        if clean_id == state_key or clean_id == data["state_name"].lower():
            return data

    # 2. Alias match (city names, abbreviations)
    for state_key, data in OFFICIAL_SDRF_ALLOCATIONS.items():
        if any(alias in clean_id or clean_id in alias for alias in data["alias_regions"]):
            return data

    # 3. Default fallback to Uttar Pradesh
    return OFFICIAL_SDRF_ALLOCATIONS["uttar-pradesh"]